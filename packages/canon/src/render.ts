import { descendants } from "./load.js";
import { renderTextTree } from "./tree.js";
import type { Canon, Finding, State } from "./types.js";

/** Past this many nodes the index shows the top levels plus one diagram per branch (REQ-6.5). */
export const MERMAID_FULL_LIMIT = 20;

const FILL: Record<State, string> = {
  stated: "#e3f5ea",
  resolved: "#e8efff",
  assumed: "#fff3d6",
  open: "#ece9fb",
  contested: "#fde7e8",
};
const STROKE: Record<State, string> = {
  stated: "#1f8a4c",
  resolved: "#2563eb",
  assumed: "#b7791f",
  open: "#6b5bd2",
  contested: "#d13438",
};

const mid = (id: string) => id.replace(/[^A-Za-z0-9]/g, "_");
const label = (id: string, title: string) => {
  const t = title.length > 48 ? title.slice(0, 47) + "…" : title;
  return `${id}<br/>${t.replace(/"/g, "#quot;").replace(/[<>]/g, "")}`;
};

function diagram(canon: Canon, ids: string[], edges: [string, string][], direction = "LR"): string {
  const lines = [`flowchart ${direction}`];
  for (const id of ids) {
    const n = canon.nodes[id];
    if (n) lines.push(`    ${mid(id)}["${label(id, n.title)}"]:::${n.state}`);
  }
  for (const [a, b] of edges) lines.push(`    ${mid(a)} --> ${mid(b)}`);
  for (const s of Object.keys(FILL) as State[]) lines.push(`    classDef ${s} fill:${FILL[s]},stroke:${STROKE[s]},color:#1a1d23`);
  return "```mermaid\n" + lines.join("\n") + "\n```";
}

function subtreeEdges(canon: Canon, root: string): [string, string][] {
  const out: [string, string][] = [];
  const visit = (id: string) => {
    for (const c of canon.nodes[id]?.children ?? []) {
      out.push([id, c]);
      visit(c);
    }
  };
  visit(root);
  return out;
}

/** The Mermaid index for GitHub and IDE previews, as a Markdown document. */
export function renderMermaidIndex(canon: Canon, findings: Finding[] = [], limit = MERMAID_FULL_LIMIT): string {
  const all = Object.keys(canon.nodes);
  const parts: string[] = [
    "---",
    "id: INDEX",
    'title: "Canon index"',
    "generated: true",
    "---",
    "",
    `# ${canon.root?.title ?? "Canon"} index`,
    "",
    "Generated by `headcanon render`. Do not edit; edit the nodes and rerun. Colors: green stated, blue resolved, amber assumed, violet open, red contested.",
    "",
  ];

  if (all.length <= limit) {
    parts.push("## Requirement tree", "", diagram(canon, all, canon.roots.flatMap((r) => subtreeEdges(canon, r))), "");
  } else {
    const top = canon.roots.flatMap((r) => [r, ...(canon.nodes[r]?.children ?? [])]);
    const topEdges = canon.roots.flatMap((r) => (canon.nodes[r]?.children ?? []).map((c): [string, string] => [r, c]));
    parts.push("## Top levels", "", diagram(canon, top, topEdges), "");
    for (const r of canon.roots) {
      const ids = [r, ...descendants(canon, r)];
      if (ids.length <= 1) continue;
      parts.push(`## ${r} ${canon.nodes[r]?.title ?? ""}`, "", diagram(canon, ids, subtreeEdges(canon, r)), "");
    }
  }

  if (canon.journeys.length) {
    parts.push("## Journeys", "");
    for (const j of canon.journeys) parts.push(`- **${j.id}** ${j.title} (${j.state}, ${j.steps.length} steps)`);
    parts.push("");
  }
  parts.push("## Text tree", "", "```", renderTextTree(canon, findings), "```", "");
  return parts.join("\n");
}
